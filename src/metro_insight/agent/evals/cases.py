def summary() -> dict:
    """문항 수 요약(표 자체 검사용)."""
    counts: dict[str, int] = {}
    splits: dict[str, int] = {}
    for case in CASES:
        counts[case["category"]] = counts.get(case["category"], 0) + 1
        splits[case["split"]] = splits.get(case["split"], 0) + 1
    return {
        "total": len(CASES),
        "by_category": dict(sorted(counts.items())),
        "by_split": dict(sorted(splits.items())),
    }